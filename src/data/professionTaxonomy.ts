export function getProfessionList() {
  return PROFESSIONS_TAXONOMY.map((p) => ({
    id: p.id,
    label: p.label,
    category: p.category,
    icon: p.icon,
  }));
}

export function findProfessionByLabel(label?: string): ProfessionDomain {
  if (!label) return PROFESSIONS_TAXONOMY[0];
  const found = PROFESSIONS_TAXONOMY.find(
    (p) =>
      p.label.toLowerCase() === label.toLowerCase() ||
      p.id.toLowerCase() === label.toLowerCase()
  );
  return found || PROFESSIONS_TAXONOMY[0];
}

export function getSubFieldsForProfession(professionLabel?: string): string[] {
  const profession = findProfessionByLabel(professionLabel);
  return profession.subFields;
}
